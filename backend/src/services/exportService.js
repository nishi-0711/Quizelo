// ─── Notes PDF Builder ────────────────────────────────────────────────────────

async function buildNotesPDF(notes) {
  return new Promise((resolve, reject) => {
    try {
      const title     = notes.title   || "Study Notes";
      const subject   = notes.subject || "";
      const sections  = Array.isArray(notes.sections) ? notes.sections : [];
      const quickRevision = Array.isArray(notes.quickRevision) ? notes.quickRevision : [];
      const dateLong  = formatDateLong();
      const dateShort = formatDate();

      const doc = new PDFDocument({
        margin: M, size: "A4", autoFirstPage: true, bufferPages: true,
        info: { Title: title, Author: "Quizelo", Creator: "Quizelo AI Notes Generator" },
      });

      const buffers = [];
      doc.on("data",  c => buffers.push(c));
      doc.on("end",   () => resolve(Buffer.concat(buffers)));
      doc.on("error", reject);

      const PAGE_GUARD = 750;
      function safeAddPage() { if (doc.y > M + 8) doc.addPage(); }
      function needsPage(h)  { return doc.y + h > PAGE_GUARD; }

      // ── Cover ─────────────────────────────────────────────────────────────
      doc.rect(0, 0, PW, 14).fill(C.brand);
      doc.rect(0, 14, PW, 5).fill(C.brandDark);

      doc.font("Helvetica-Bold").fontSize(36).fillColor(C.brand).text("QUIZELO", M, 46);
      doc.font("Helvetica").fontSize(12).fillColor(C.light).text("AI Study Notes Generator", M, 90);

      doc.moveTo(M, 116).lineTo(PW - M, 116).strokeColor(C.brand).lineWidth(2.5).stroke();
      doc.moveTo(M, 121).lineTo(PW - M, 121).strokeColor(C.divider).lineWidth(0.5).stroke();

      // Card
      const cX = M, cY = 138, cW = CW, cH = 228;
      doc.rect(cX + 3, cY + 3, cW, cH).fill("#dde1ea");
      doc.roundedRect(cX, cY, cW, cH, 7).fillAndStroke(C.white, C.divider);
      doc.moveTo(cX + 165, cY + 20).lineTo(cX + 165, cY + cH - 20).strokeColor(C.divider).lineWidth(0.5).stroke();

      const coverRows = [
        ["Document Title", title.slice(0, 55), true],
        ["Subject",        subject || "General", false],
        ["Generated On",   dateLong, false],
        ["Sections",       String(sections.length), false],
      ];
      let rY = cY + 26;
      coverRows.forEach(([label, value, big], ri) => {
        doc.font("Helvetica-Bold").fontSize(7.5).fillColor(C.light).text(label.toUpperCase(), cX + 16, rY, { width: 138, lineBreak: false });
        doc.font("Helvetica-Bold").fontSize(big ? 13.5 : 11.5).fillColor(C.dark).text(value, cX + 177, rY - (big ? 2 : 0), { width: cW - 193, lineBreak: false, ellipsis: true });
        rY += 44;
        if (ri < coverRows.length - 1) {
          doc.moveTo(cX + 16, rY - 12).lineTo(cX + cW - 16, rY - 12).strokeColor(C.divider).lineWidth(0.3).stroke();
        }
      });

      doc.rect(0, PH - 44, PW, 44).fill(C.bg);
      doc.font("Helvetica").fontSize(8.5).fillColor(C.light).text("Quizelo  |  AI-Powered Study Notes", M, PH - 26, { align: "center", width: CW, lineBreak: false });

      // ── Content pages ─────────────────────────────────────────────────────
      doc.addPage();

      sections.forEach((sec, si) => {
        if (needsPage(80)) safeAddPage();

        // Section header
        const shY = doc.y;
        doc.rect(M, shY, CW, 30).fill(C.bg);
        doc.rect(M, shY, 5, 30).fill(C.brand);
        doc.font("Helvetica-Bold").fontSize(13).fillColor(C.dark).text(sec.chapter || `Section ${si + 1}`, M + 14, shY + 8, { width: CW - 20, lineBreak: false });
        doc.y = shY + 42;

        // Summary
        if (sec.summary) {
          doc.font("Helvetica-Oblique").fontSize(10.5).fillColor(C.mid).text(sec.summary, M, doc.y, { width: CW, lineBreak: true });
          doc.y += 10;
        }

        // ── Key Concepts ────────────────────────────────────────────────────
        if (Array.isArray(sec.keyConcepts) && sec.keyConcepts.length > 0) {
          if (needsPage(50)) safeAddPage();
          doc.font("Helvetica-Bold").fontSize(9).fillColor(C.brand).text("KEY CONCEPTS", M, doc.y);
          doc.y += 6;
          // Render as pill-like inline tags
          const pillH = 18; const pillGap = 6;
          let px = M;
          sec.keyConcepts.forEach(concept => {
            const w = Math.min(doc.font("Helvetica").fontSize(9).widthOfString(concept) + 20, CW);
            if (px + w > PW - M) { px = M; doc.y += pillH + pillGap; }
            if (needsPage(pillH + pillGap)) { safeAddPage(); px = M; }
            doc.roundedRect(px, doc.y, w, pillH, 3).fillAndStroke(C.bg, C.divider);
            doc.font("Helvetica").fontSize(8.5).fillColor(C.mid).text(concept, px + 10, doc.y + 4, { lineBreak: false });
            px += w + pillGap;
          });
          doc.y += pillH + 14;
        }

        // ── Definitions ─────────────────────────────────────────────────────
        if (Array.isArray(sec.definitions) && sec.definitions.length > 0) {
          if (needsPage(60)) safeAddPage();
          doc.font("Helvetica-Bold").fontSize(9).fillColor(C.brand).text("DEFINITIONS", M, doc.y);
          doc.y += 8;
          sec.definitions.forEach(def => {
            if (needsPage(36)) safeAddPage();
            doc.font("Helvetica-Bold").fontSize(10).fillColor(C.dark).text(def.term + ":", M, doc.y, { lineBreak: false });
            doc.y += 14;
            doc.font("Helvetica").fontSize(10).fillColor(C.mid).text(def.definition, M + 16, doc.y, { width: CW - 16, lineBreak: true });
            doc.y += 10;
          });
          doc.y += 4;
        }

        // ── Formulas ────────────────────────────────────────────────────────
        if (Array.isArray(sec.formulas) && sec.formulas.length > 0) {
          if (needsPage(50)) safeAddPage();
          doc.font("Helvetica-Bold").fontSize(9).fillColor(C.brand).text("FORMULAS", M, doc.y);
          doc.y += 8;
          sec.formulas.forEach(formula => {
            if (needsPage(28)) safeAddPage();
            const fY = doc.y;
            doc.rect(M, fY, CW, 22).fill(C.bg);
            doc.font("Helvetica-Bold").fontSize(10.5).fillColor(C.dark).text(formula, M + 12, fY + 5, { width: CW - 20, lineBreak: false, ellipsis: true });
            doc.y = fY + 28;
          });
          doc.y += 4;
        }

        // ── Key Takeaways ────────────────────────────────────────────────────
        if (Array.isArray(sec.keyTakeaways) && sec.keyTakeaways.length > 0) {
          if (needsPage(50)) safeAddPage();
          doc.font("Helvetica-Bold").fontSize(9).fillColor(C.brand).text("KEY TAKEAWAYS", M, doc.y);
          doc.y += 8;
          sec.keyTakeaways.forEach(tk => {
            if (needsPage(22)) safeAddPage();
            doc.rect(M + 2, doc.y + 5, 5, 5).fill(C.brand);
            doc.font("Helvetica").fontSize(10).fillColor(C.mid).text(tk, M + 16, doc.y, { width: CW - 16, lineBreak: true });
            doc.y += 6;
          });
          doc.y += 4;
        }

        // Section divider
        doc.y += 8;
        doc.moveTo(M, doc.y).lineTo(PW - M, doc.y).strokeColor(C.divider).lineWidth(0.5).stroke();
        doc.y += 20;
      });

      // ── Quick Revision ────────────────────────────────────────────────────
      if (quickRevision.length > 0) {
        safeAddPage();
        const qrY = doc.y;
        doc.rect(M, qrY, CW, 32).fill(C.brand);
        doc.font("Helvetica-Bold").fontSize(14).fillColor(C.white).text("Quick Revision", M + 16, qrY + 8, { lineBreak: false });
        doc.y = qrY + 44;

        quickRevision.forEach((item, qi) => {
          if (needsPage(26)) safeAddPage();
          const rowY = doc.y;
          const isEven = qi % 2 === 0;
          doc.rect(M, rowY, CW, 24).fill(isEven ? C.bg : C.white);
          doc.font("Helvetica-Bold").fontSize(8.5).fillColor(C.brand).text(`${qi + 1}.`, M + 10, rowY + 7, { lineBreak: false });
          doc.font("Helvetica").fontSize(9.5).fillColor(C.dark).text(item, M + 28, rowY + 6, { width: CW - 34, lineBreak: false, ellipsis: true });
          doc.y = rowY + 26;
        });
      }

      // ── Post-process headers/footers ──────────────────────────────────────
      const range = doc.bufferedPageRange();
      const contentCount = range.count - 1;
      for (let pi = 1; pi < range.count; pi++) {
        doc.switchToPage(pi);
        _drawHeader(doc, title, pi);
        _drawFooter(doc, pi, contentCount, dateShort);
      }

      doc.flushPages();
      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

// ─── Notes DOCX Builder ───────────────────────────────────────────────────────

async function buildNotesDOCX(notes) {
  const title    = notes.title   || "Study Notes";
  const subject  = notes.subject || "";
  const sections = Array.isArray(notes.sections) ? notes.sections : [];
  const quickRevision = Array.isArray(notes.quickRevision) ? notes.quickRevision : [];
  const dateLong = formatDateLong();

  const children = [];

  // Cover header
  children.push(new Paragraph({ children: [new TextRun({ text: "QUIZELO", bold: true, size: 56, color: "4f46e5" })], alignment: AlignmentType.CENTER, spacing: { after: 80 } }));
  children.push(new Paragraph({ children: [new TextRun({ text: "AI Study Notes Generator", size: 22, color: "94a3b8" })], alignment: AlignmentType.CENTER, spacing: { after: 300 } }));
  children.push(new Paragraph({ text: title, heading: HeadingLevel.HEADING_1, spacing: { after: 100 } }));
  if (subject) children.push(new Paragraph({ children: [new TextRun({ text: `Subject: ${subject}`, color: "475569", size: 22 })], spacing: { after: 80 } }));
  children.push(new Paragraph({ children: [new TextRun({ text: `Generated: ${dateLong}  |  ${sections.length} sections`, color: "94a3b8", size: 20 })], spacing: { after: 400 } }));
  children.push(new Paragraph({ border: { bottom: { color: "4f46e5", space: 1, value: BorderStyle.SINGLE, size: 12 } }, spacing: { after: 400 } }));

  sections.forEach((sec, si) => {
    children.push(new Paragraph({ text: sec.chapter || `Section ${si + 1}`, heading: HeadingLevel.HEADING_2, spacing: { before: 400, after: 160 } }));

    if (sec.summary) {
      children.push(new Paragraph({ children: [new TextRun({ text: sec.summary, italics: true, size: 22, color: "475569" })], spacing: { after: 200 } }));
    }

    if (Array.isArray(sec.keyConcepts) && sec.keyConcepts.length > 0) {
      children.push(new Paragraph({ children: [new TextRun({ text: "Key Concepts", bold: true, size: 22, color: "4f46e5" })], spacing: { before: 160, after: 80 } }));
      children.push(new Paragraph({ children: [new TextRun({ text: sec.keyConcepts.join("  ·  "), size: 20, color: "475569" })], spacing: { after: 160 } }));
    }

    if (Array.isArray(sec.definitions) && sec.definitions.length > 0) {
      children.push(new Paragraph({ children: [new TextRun({ text: "Definitions", bold: true, size: 22, color: "4f46e5" })], spacing: { before: 160, after: 80 } }));
      sec.definitions.forEach(def => {
        children.push(new Paragraph({ children: [new TextRun({ text: `${def.term}:  `, bold: true, size: 22 }), new TextRun({ text: def.definition, size: 20, color: "475569" })], spacing: { after: 80 }, indent: { left: 360 } }));
      });
    }

    if (Array.isArray(sec.formulas) && sec.formulas.length > 0) {
      children.push(new Paragraph({ children: [new TextRun({ text: "Formulas", bold: true, size: 22, color: "4f46e5" })], spacing: { before: 160, after: 80 } }));
      sec.formulas.forEach(f => {
        children.push(new Paragraph({ children: [new TextRun({ text: f, bold: true, size: 22, color: "1e293b" })], spacing: { after: 80 }, indent: { left: 360 } }));
      });
    }

    if (Array.isArray(sec.keyTakeaways) && sec.keyTakeaways.length > 0) {
      children.push(new Paragraph({ children: [new TextRun({ text: "Key Takeaways", bold: true, size: 22, color: "4f46e5" })], spacing: { before: 160, after: 80 } }));
      sec.keyTakeaways.forEach(tk => {
        children.push(new Paragraph({ children: [new TextRun({ text: `• ${tk}`, size: 20, color: "1e293b" })], spacing: { after: 80 }, indent: { left: 360 } }));
      });
    }

    children.push(new Paragraph({ border: { bottom: { color: "e2e8f0", space: 1, value: BorderStyle.SINGLE, size: 6 } }, spacing: { after: 200 } }));
  });

  if (quickRevision.length > 0) {
    children.push(new Paragraph({ text: "Quick Revision", heading: HeadingLevel.HEADING_1, pageBreakBefore: true, spacing: { before: 200, after: 300 } }));
    quickRevision.forEach((item, qi) => {
      children.push(new Paragraph({ children: [new TextRun({ text: `${qi + 1}.  `, bold: true, size: 22 }), new TextRun({ text: item, size: 22, color: "1e293b" })], spacing: { after: 100 } }));
    });
  }

  const docx = new Document({ creator: "Quizelo", title, sections: [{ properties: {}, children }] });
  return Packer.toBuffer(docx);
}

