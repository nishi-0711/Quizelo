// ─── Helpers ──────────────────────────────────────────────────────────────────

function formatDate(d = new Date()) {
  return d.toISOString().slice(0, 10); // YYYY-MM-DD
}

function formatDateLong(d = new Date()) {
  try {
    return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
  } catch {
    return formatDate(d);
  }
}

function getFilename(pdfName, format) {
  const base = (pdfName || "Quiz")
    .replace(/\.pdf$/i, "")
    .replace(/[^a-zA-Z0-9_\-]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "")
    .slice(0, 60);
  const ext = format === "docx" ? "docx" : "pdf";
  return `Quiz_${base}_${formatDate()}.${ext}`;
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function prepareQuestions(questions, settings) {
  let qs = questions.map((q) => ({ ...q }));
  if (settings.shuffleQuestions) qs = shuffle(qs);
  if (settings.shuffleOptions) {
    qs = qs.map((q) => {
      if (q.type !== "mcq" || !Array.isArray(q.options)) return q;
      const correct = q.options[q.answerIndex];
      const newOpts = shuffle(q.options);
      return { ...q, options: newOpts, answerIndex: newOpts.indexOf(correct) };
    });
  }
  return qs;
}

function getAnswerLabel(q) {
  if (q.type === "mcq") return `${String.fromCharCode(65 + q.answerIndex)}) ${q.options[q.answerIndex]}`;
  if (q.type === "true_false") return q.answer ? "True" : "False";
  return q.answer || "";
}

// Short form used in answer key table column (avoids wrapping)
function getAnswerShort(q) {
  if (q.type === "mcq") return String.fromCharCode(65 + q.answerIndex);
  if (q.type === "true_false") return q.answer ? "True" : "False";
  const ans = String(q.answer || "");
  return ans.length > 22 ? ans.slice(0, 20) + "..." : ans;
}

function capitalize(s) {
  if (!s) return "";
  return s.charAt(0).toUpperCase() + s.slice(1).replace(/_/g, " ");
}

